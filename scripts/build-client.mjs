import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import vm from 'node:vm';
const source = await readFile(new URL('../client/index.js', import.meta.url), 'utf8');
const output = `// Generated by scripts/build-client.mjs; edit client/index.js.\nwindow.__ModuleLoader__.load({\n  id: 'dsh-kook',\n  factory: (require) => {\n    const exports = {};\n${source.split('\n').map(line => `    ${line}`).join('\n')}\n    return exports;\n  }\n});\n`;
new vm.Script(output, { filename: 'src/client.js' });
await writeFile(new URL('../src/client.js', import.meta.url), output);
console.log(`Built ${fileURLToPath(new URL('../src/client.js', import.meta.url))}`);
